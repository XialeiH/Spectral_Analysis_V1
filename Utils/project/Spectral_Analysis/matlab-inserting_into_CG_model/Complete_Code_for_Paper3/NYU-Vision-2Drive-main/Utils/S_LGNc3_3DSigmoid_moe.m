function y = S_LGNc3_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_S_LGN3.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0119018443, -0.0016272286, -0.0303008873; ...
    -0.0007185817, 0.0013445418, 0.0584773719; ...
    0.0154973809, 0.0172098055, 0.0189016499];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.8020573258;   p0.a2 = -1.8718904257;   p0.a3 = 3.2361645699;
p0.c1a = -0.3333019614; p0.c1b = 0.5405706763; p0.c1c = -31.2233619690;
p0.c2a = 0.5119140744; p0.c2b = 2.5268001556; p0.c2c = 0.2867530584;
p0.c3a = -1.8424451351; p0.c3b = 0.4369639754; p0.c3c = -23.5758552551;
p0.L = 34.0454978943;     p0.k = 5.5326633453;    p0.x0 = -0.5940101147;
p0.L1 = 1.7849459648;   p0.k1 = 1.8873791695;   p0.x01 = 0.4780924320;
p0.L2 = 0.5862050056;   p0.k2 = 13.6477403641;   p0.x02 = -1.4373338223;
p0.L3 = 0.7947916389;   p0.k3 = 0.5098751783;   p0.x03 = -2.9348139763;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.8162574172;   p1.a2 = -1.7628389597;   p1.a3 = 3.0062899590;
p1.c1a = -0.1971802115; p1.c1b = 0.4167657793; p1.c1c = -36.4046974182;
p1.c2a = 0.5161016583; p1.c2b = 2.5365347862; p1.c2c = 0.2867530584;
p1.c3a = -1.8508232832; p1.c3b = 0.8366366029; p1.c3c = -28.0679225922;
p1.L = 75.9281158447;     p1.k = 4.3585867882;    p1.x0 = 0.4112522304;
p1.L1 = 1.7276760340;   p1.k1 = 1.9925262928;   p1.x01 = 0.5678579807;
p1.L2 = 0.3901235163;   p1.k2 = 13.6681051254;   p1.x02 = -1.5809916258;
p1.L3 = 0.4370627105;   p1.k3 = 0.4859752655;   p1.x03 = -3.6475057602;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.7132195234;   p2.a2 = -1.7733534575;   p2.a3 = 3.0173110962;
p2.c1a = -0.1687040627; p2.c1b = 0.3363985717; p2.c1c = -40.5861358643;
p2.c2a = 0.5218050480; p2.c2b = 2.5389013290; p2.c2c = 0.2867960036;
p2.c3a = -0.9215629697; p2.c3b = -1.3017702103; p2.c3c = -30.6318759918;
p2.L = 130.8728942871;     p2.k = 3.9919593334;    p2.x0 = 3.1154329777;
p2.L1 = 1.6736087799;   p2.k1 = 2.3323273659;   p2.x01 = 0.4901614785;
p2.L2 = 0.1796747297;   p2.k2 = 13.6771907806;   p2.x02 = -1.6317883730;
p2.L3 = 0.2647455335;   p2.k3 = 0.4743029475;   p2.x03 = -4.1200623512;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
