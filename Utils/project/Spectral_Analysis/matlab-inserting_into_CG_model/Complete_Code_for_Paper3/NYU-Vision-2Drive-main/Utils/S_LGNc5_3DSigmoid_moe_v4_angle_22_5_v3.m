    phi3 = p.r3_L ./ (1 + exp(-p.r3_k .* (z3 - p.r3_x0)));

    r1 = base1 + phi1 * p.u1.';
    r2 = base2 + phi2 * p.u2.';
    r3 = base3 + phi3 * p.u3.';

