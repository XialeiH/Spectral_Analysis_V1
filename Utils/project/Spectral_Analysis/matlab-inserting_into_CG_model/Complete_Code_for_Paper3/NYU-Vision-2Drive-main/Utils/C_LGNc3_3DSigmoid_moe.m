function y = C_LGNc3_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_C_LGN3.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0014650413, -0.0013264398, 0.0082004378; ...
    -0.0065480694, -0.0139256045, 0.0182906426; ...
    0.0026658738, 0.0056253676, -0.0056637828];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.8493252993;   p0.a2 = -1.8427071571;   p0.a3 = 3.1276788712;
p0.c1a = -0.2493676394; p0.c1b = 0.4480042160; p0.c1c = -31.4423503876;
p0.c2a = 0.5119140744; p0.c2b = 2.5268001556; p0.c2c = 0.2867530584;
p0.c3a = -2.0779030323; p0.c3b = 0.3078339100; p0.c3c = -23.7382202148;
p0.L = 33.9340782166;     p0.k = 5.1563777924;    p0.x0 = -0.4993722737;
p0.L1 = 1.8271707296;   p0.k1 = 1.8355776072;   p0.x01 = 0.4327179492;
p0.L2 = 0.5570243001;   p0.k2 = 13.6477403641;   p0.x02 = -1.4373388290;
p0.L3 = 0.6855319142;   p0.k3 = 0.4019234180;   p0.x03 = -2.8218679428;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.8003622890;   p1.a2 = -1.8589842319;   p1.a3 = 2.9453380108;
p1.c1a = -0.1973192692; p1.c1b = 0.4160599709; p1.c1c = -36.3979148865;
p1.c2a = 0.5161016583; p1.c2b = 2.5365347862; p1.c2c = 0.2867530584;
p1.c3a = -1.8485139608; p1.c3b = 0.8234555125; p1.c3c = -28.0700035095;
p1.L = 75.8315200806;     p1.k = 4.5280075073;    p1.x0 = 0.6902264357;
p1.L1 = 1.7128512859;   p1.k1 = 2.0095348358;   p1.x01 = 0.5832605362;
p1.L2 = 0.4857627749;   p1.k2 = 13.6681051254;   p1.x02 = -1.5810002089;
p1.L3 = 0.3792904615;   p1.k3 = 0.4456315041;   p1.x03 = -3.5826206207;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.8041065931;   p2.a2 = -1.5871170759;   p2.a3 = 2.6371510029;
p2.c1a = -0.2327813208; p2.c1b = 0.3411786556; p2.c1c = -40.8168716431;
p2.c2a = 0.5218050480; p2.c2b = 2.5389013290; p2.c2c = 0.2867960036;
p2.c3a = -1.0075156689; p2.c3b = -1.3551876545; p2.c3c = -31.5737190247;
p2.L = 130.2883758545;     p2.k = 5.2322716713;    p2.x0 = 3.9024534225;
p2.L1 = 1.7092345953;   p2.k1 = 2.5787644386;   p2.x01 = 0.6189048886;
p2.L2 = -0.0056335707;   p2.k2 = 13.6771907806;   p2.x02 = -1.6317883730;
p2.L3 = 0.3633584976;   p2.k3 = 0.5411380529;   p2.x03 = -3.4656167030;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
