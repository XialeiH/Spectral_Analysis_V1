b2 = [0.5308037400, -1.5330618620, 0.4700423479];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.3972291946;   p0.a2 = -2.4877381325;   p0.a3 = 2.9565191269;
