% Gate fc2 -> logits
W2 = [
  -1.3426648378, -1.1707051992, -0.8830114603, -1.4205756187, -0.7785298228, 1.7331802845, -1.0783181190, 3.1309525967, 1.1341531277, -2.2814891338, 1.0337158442, -2.7608387470;
