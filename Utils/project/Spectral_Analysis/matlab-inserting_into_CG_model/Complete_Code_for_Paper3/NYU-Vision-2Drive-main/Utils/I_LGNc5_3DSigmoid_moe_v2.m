% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25719.2011718750, 18775.4824218750, 19.6888484955];
sd = [13425.0302734375, 8271.6806640625, 11.1974649429];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  1.5944024324, -0.4822891653, 0.3325989842;
  1.8352977037, -1.2895655632, 0.0371915996;
  2.1077694893, -1.1725231409, -0.2931675613;
  0.3683525324, -1.3196144104, 0.2214706242;
  0.5962298512, -1.3832045794, 0.4540325701;
  -1.8239623308, 0.3431246579, 0.0224366467;
  1.7929681540, -0.5509329438, -0.1737371385;
  -0.0235544071, -2.1249189377, 0.2708165646;
  -1.6802909374, 0.8155285120, 0.1696980894;
  1.2030004263, -1.8600726128, 0.7715225220;
  -2.6931943893, 1.2675172091, -0.2748366892;
  1.4357910156, -2.1106050014, 0.5511510968
];
