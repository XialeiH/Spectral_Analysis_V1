% Gate normalization
mu = [24776.8710937500, 16070.2744140625, 20.9011077881];
sd = [13415.9375000000, 7432.9072265625, 11.1676998138];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  -1.1294392347, 0.2194104493, -0.1059907451;
  0.4315189421, -0.4514416158, 0.4436388910;
  0.7123678923, -0.3937193751, 0.1404898912;
  -0.2412275374, 1.6918400526, -0.4702976942;
