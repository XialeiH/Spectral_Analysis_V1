function y = eval_expert_v6(X, p)
    x1 = X(:,1); x2 = X(:,2); x3 = X(:,3);
    b1_lin = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2_lin = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3_lin = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1 .* (b1_lin - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2 .* (b2_lin - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3 .* (b3_lin - p.x03)));

    s = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(s - p.x0)));
end
