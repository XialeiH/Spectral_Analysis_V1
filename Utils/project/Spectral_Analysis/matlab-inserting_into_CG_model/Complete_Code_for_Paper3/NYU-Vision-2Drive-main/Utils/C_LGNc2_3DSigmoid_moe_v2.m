function y = C_LGNc2_3DSigmoid_moe_v2(L4EUse, L4IUse, L6Use) %#codegen
% MoE v2 sigmoid generated from moe_C_LGN2_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25164.4238281250, 18169.6621093750, 17.8853607178];
sd = [13497.5292968750, 8433.7167968750, 10.8319978714];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  -0.8587355018, 0.7878029346, -0.4404924512;
  0.8472620845, -0.6479480267, 0.3452339768;
  -1.0386061668, 0.6908450127, 0.0857301652;
  0.0341505446, 0.0580036007, 0.1246846244;
  0.8994737864, -0.3743681610, -0.0935946628;
  1.0595837831, -0.6654920578, 0.1189694107;
  -0.6885688901, 0.3686459959, -0.2000666857;
  1.1258115768, -1.3331913948, 0.7988681197;
  -0.8438542485, 0.5545608401, -0.2535705864;
  -0.4407894909, 0.0180335715, -0.2341590971;
  -0.5825654268, 0.3480702341, -0.2696993351;
  -0.1631271839, 0.0849036872, 0.3476002514
];
b1 = [-0.2794335783, 0.5996788144, -0.4482440948, 0.9199265242, 0.8774839044, 0.9313191772, -0.5936223269, 0.2401709706, -0.6808043718, -0.4024435580, -0.3560657501, 0.0412531160];
h = tanh(xg * W1.' + b1);

% Gate fc2 -> logits
W2 = [
  0.7213240862, -0.7286039591, 0.7488023043, -0.0771173164, -1.0361360312, -0.6945883036, 0.8424725533, -0.6482863426, 0.7502853274, 0.6488665938, 0.8678163886, -0.0388644375;
  0.4517189562, -0.2190587074, 0.4966751635, 0.0208139010, -0.2937939167, -0.3569699824, -0.2416075021, -0.4036795795, 0.2117664665, 0.0375456959, -0.1821551770, 0.3393159509;
  -0.6023171544, 0.5774809122, -0.6303849816, -0.0715248808, 0.5702233315, 0.5314101577, -0.6381484270, 0.5404956937, -0.6475331783, -0.2948343158, -0.7120952606, -0.2692160904
];
b2 = [-0.1381571740, 0.0477960519, -0.1108018309];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.1100250483;   p0.a2 = -1.7735412121;   p0.a3 = 3.7596755028;
p0.c1a = -0.1027896106; p0.c1b = 0.1331420094; p0.c1c = -15.1084671021;
p0.c2a = 0.5853922367; p0.c2b = 2.6235127449; p0.c2c = 0.3780990243;
p0.c3a = -0.8438908458; p0.c3b = 0.3971499503; p0.c3c = -48.6274795532;
p0.L = 38.7425651550;     p0.k = 5.8068742752;    p0.x0 = 2.2605016232;
p0.L1 = 1.7063463926;   p0.k1 = 5.6991047859;   p0.x01 = 0.0382460020;
p0.L2 = 0.6210045815;   p0.k2 = 13.7969989777;   p0.x02 = -1.5746834278;
p0.L3 = 0.5030427575;   p0.k3 = 2.9604184628;   p0.x03 = -0.8805820942;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.9062236547;   p1.a2 = -1.5316317081;   p1.a3 = 3.1495010853;
p1.c1a = -0.0974782035; p1.c1b = 0.1221087277; p1.c1c = -11.3750133514;
