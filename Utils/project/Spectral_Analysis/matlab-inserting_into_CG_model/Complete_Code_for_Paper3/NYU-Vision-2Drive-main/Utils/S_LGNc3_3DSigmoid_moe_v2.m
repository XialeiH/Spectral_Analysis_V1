p0.c3a = -2.1141304970; p0.c3b = 0.2382678390; p0.c3c = -23.7639217377;
p0.L = 34.1796226501;     p0.k = 5.5412263870;    p0.x0 = -0.6433178186;
p0.L1 = 1.8819870949;   p0.k1 = 1.7124994993;   p0.x01 = 0.3710683286;
p0.L2 = 0.6828900576;   p0.k2 = 13.6477403641;   p0.x02 = -1.4373338223;
p0.L3 = 0.6557989120;   p0.k3 = 0.3689810634;   p0.x03 = -2.8049626350;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.7870215178;   p1.a2 = -1.7398024797;   p1.a3 = 2.9607939720;
p1.c1a = -0.1990233809; p1.c1b = 0.3870389760; p1.c1c = -36.4325141907;
