function y = S_LGNc3_3DSigmoid_moe_v2(L4EUse, L4IUse, L6Use) %#codegen
% MoE v2 sigmoid generated from moe_S_LGN3_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25189.2753906250, 15937.7343750000, 21.5177764893];
sd = [13303.9072265625, 7306.6782226562, 11.2011156082];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  -1.6374925375, 3.0120041370, -0.8914605379;
  0.2395510823, 0.4853910208, 0.4524039030;
  -0.4325799644, -1.0573121309, -0.0363795795;
  -0.2720551193, 0.1567994207, -0.6115946770;
  -1.2423759699, 2.4702687263, -1.0915021896;
  -0.2365131974, -1.6288805008, 0.8088814020;
  -0.9446264505, 0.2585562766, 0.3851205707;
  1.0059709549, -1.7678418159, 0.3389343321;
  -2.0305075645, 2.0596790314, -0.6206504107;
  0.2580482364, 0.4739982784, -0.1676743329;
  -1.0973472595, 1.7628622055, -0.5603652000;
  0.8845860958, -1.4088255167, -0.2217651308
];
b1 = [1.4557149410, -0.6430668235, -2.5960259438, 0.1766066253, 0.8155481815, -3.6409111023, -1.5309833288, 0.4068453014, -0.9045598507, 0.7323417664, 0.6209217310, -0.5045475364];
h = tanh(xg * W1.' + b1);

% Gate fc2 -> logits
W2 = [
  1.7510772943, -1.4930069447, 1.8535974026, 1.2969375849, 1.2800223827, 2.9546608925, 1.2560374737, -0.5939772129, 1.2433038950, -2.2356071472, 1.0557771921, -0.6087812781;
  0.0421468094, 0.4887561798, -0.1724260449, -0.1706939191, -0.9358161092, -1.4485746622, -1.1153929234, -0.5796159506, -0.2577039003, 0.1030590832, 0.4396570623, -0.8673934937;
  -1.1174702644, 0.9169569016, -1.8737465143, -1.1558064222, -0.7677244544, -0.4370159209, -0.4720180631, 0.6861724257, -0.6362861395, 1.5852072239, -0.9108563066, 0.7749065161
];
b2 = [1.0206750631, -0.0519846603, -0.1853556335];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.9136702418;   p0.a2 = -1.9698711634;   p0.a3 = 3.1004014015;
p0.c1a = -0.2568680942; p0.c1b = 0.4312906563; p0.c1c = -31.4759140015;
