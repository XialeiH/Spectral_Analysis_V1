p1.L2 = 0.3670192957;   p1.k2 = 13.6681051254;   p1.x02 = -1.5809916258;
p1.L3 = 0.3904703856;   p1.k3 = 0.5023987889;   p1.x03 = -3.7092058659;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.7847405672;   p2.a2 = -1.7082568407;   p2.a3 = 2.9840128422;
