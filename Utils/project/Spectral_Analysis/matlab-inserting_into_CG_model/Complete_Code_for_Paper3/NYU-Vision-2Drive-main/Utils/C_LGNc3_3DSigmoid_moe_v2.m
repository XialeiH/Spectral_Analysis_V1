p0.c3a = -1.9917615652; p0.c3b = 0.2982673347; p0.c3c = -23.7129688263;
p0.L = 33.3862495422;     p0.k = 5.6101865768;    p0.x0 = -0.2060027421;
p0.L1 = 1.9093643427;   p0.k1 = 1.8084520102;   p0.x01 = 0.3204028606;
p0.L2 = 0.8978567719;   p0.k2 = 13.6477403641;   p0.x02 = -1.4373351336;
p0.L3 = 0.3822247982;   p0.k3 = -0.0233206581;   p0.x03 = -2.6703414917;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.7882850170;   p1.a2 = -1.8461455107;   p1.a3 = 3.2020475864;
