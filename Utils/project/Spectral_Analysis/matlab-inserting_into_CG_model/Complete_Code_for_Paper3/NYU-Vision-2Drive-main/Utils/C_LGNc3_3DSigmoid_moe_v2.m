function y = C_LGNc3_3DSigmoid_moe_v2(L4EUse, L4IUse, L6Use) %#codegen
% MoE v2 sigmoid generated from moe_C_LGN3_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25164.9277343750, 18169.9355468750, 17.8852863312];
sd = [13498.0478515625, 8434.1279296875, 10.8322486877];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  -0.0215282198, -0.3397932947, 0.1764789671;
  -1.6754442453, 0.6491453052, -0.1556980759;
  1.2517012358, -0.1247933805, 0.2276736051;
  1.0653662682, -0.7398253083, 0.5095759630;
  -1.4147573709, 1.3519052267, -0.3155238926;
  -0.7689587474, 1.1154580116, -0.5314517021;
  1.0321255922, -0.6218642592, 0.0524342842;
  0.5998754501, -0.4820385277, 0.1229684576;
  0.0414616801, -1.0235986710, 0.0297302231;
  0.0306813475, -0.4979489446, -0.2487200946;
  1.4636886120, -1.6603082418, 0.4541189671;
  1.5594451427, -2.0127236843, 0.5565966368
];
b1 = [1.0209259987, -1.9304268360, 2.4376218319, 1.0648034811, -0.3556207716, 0.1895847917, -0.3376780748, -0.2636979818, -2.1357810497, -0.0349610671, 0.2295693904, -0.8859103322];
h = tanh(xg * W1.' + b1);

% Gate fc2 -> logits
W2 = [
  0.5630937219, 1.1453074217, -0.9901658297, -0.7859272957, 0.9451976418, 0.9124094248, -0.9802109003, -0.6713420749, 1.1624603271, -0.3524851799, -1.0153857470, -0.7724839449;
  -0.8337997198, -1.0886827707, 0.2382433563, 0.9850803018, -1.3315421343, -0.4320132732, -0.1105841696, -1.1482368708, 1.1188372374, -0.2544097006, 1.4398015738, -1.0064222813;
  0.3434243202, -0.4317088127, 0.7664723396, -0.3833675385, -0.2898105979, -0.8465462923, 0.8742151856, 1.7575356960, -1.5088728666, 0.3964142501, 0.2644338608, 1.0043127537
];
b2 = [0.1419156492, -1.1551883221, 0.4076549411];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.9272859693;   p0.a2 = -2.1854708195;   p0.a3 = 2.8278853893;
