h = tanh(xg * W1.' + b1);

% Gate fc2 -> logits
W2 = [
  -2.1408679485, -2.1582641602, 0.8739246726, 0.6055536866, 0.1606900096, -1.4967402220, -1.5951585770, -0.9707387686, -0.8205870390, -0.6948135495, -0.4017755091, 1.5610473156;
  1.4416646957, 1.3077790737, 0.6798416376, 0.9206783175, -0.6799997687, -1.3097778559, -1.2308962345, -0.0587826632, 1.0410611629, 0.9772087336, -1.1009316444, 1.7276400328;
  1.7770740986, 1.7495225668, -0.8078348637, -1.2074407339, 0.9757657051, 1.4815974236, 1.5627870560, 1.2809534073, -0.2396293432, -0.0323449858, 1.1819173098, -1.8002278805
];
b2 = [0.5723729730, -1.0063915253, 0.1923334002];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.5738545656;   p0.a2 = -2.2802035809;   p0.a3 = 2.8046128750;
