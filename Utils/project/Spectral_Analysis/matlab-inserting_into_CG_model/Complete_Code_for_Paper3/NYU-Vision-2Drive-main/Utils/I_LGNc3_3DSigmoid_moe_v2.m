function y = I_LGNc3_3DSigmoid_moe_v2(L4EUse, L4IUse, L6Use) %#codegen
% MoE v2 sigmoid generated from moe_I_LGN3_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25493.0566406250, 19137.3867187500, 18.9525299072];
sd = [13487.8271484375, 8230.5839843750, 11.0809030533];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  2.5845382214, -1.8156697750, 0.8015534878;
  2.8822941780, -1.4960668087, 0.3437903225;
  -1.0757250786, 1.2697280645, -0.0487115867;
  0.5438340902, -0.0919626057, -0.1154846549;
  -0.0515340790, 0.2064752728, -0.2771619856;
  2.0364603996, -2.3467812538, 0.3838610947;
  1.6864441633, -2.3336441517, 0.1664689779;
  1.8094480038, -0.8321173191, 0.4231840670;
  -0.0200700406, -0.7828048468, 0.0169730932;
  0.3540746570, -0.3142749369, -0.1913396865;
  0.4447688460, -1.1934269667, 0.1145632416;
  -2.6539015770, 2.6811485291, -0.5506292582
];
