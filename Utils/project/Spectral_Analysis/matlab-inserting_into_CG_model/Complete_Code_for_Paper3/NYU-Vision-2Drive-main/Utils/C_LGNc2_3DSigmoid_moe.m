function y = C_LGNc2_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_C_LGN2.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    0.0108801657, -0.0040454543, 0.0669495836; ...
    -0.0247567892, -0.0081131142, -0.0819782615; ...
    0.0338455886, 0.0310472455, 0.0595664494];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.0324690342;   p0.a2 = -1.6263073683;   p0.a3 = 3.7097108364;
p0.c1a = -0.1345862299; p0.c1b = 0.1214694455; p0.c1c = -15.1352434158;
p0.c2a = 0.5853922367; p0.c2b = 2.6235127449; p0.c2c = 0.3780990243;
p0.c3a = -0.8229303956; p0.c3b = 0.4732278287; p0.c3c = -48.5999259949;
p0.L = 38.7026710510;     p0.k = 5.4500756264;    p0.x0 = 2.1355102062;
p0.L1 = 1.5908838511;   p0.k1 = 5.7269134521;   p0.x01 = 0.1355091929;
p0.L2 = 0.4740010798;   p0.k2 = 13.7969989777;   p0.x02 = -1.5746834278;
p0.L3 = 0.4188566804;   p0.k3 = 2.7231423855;   p0.x03 = -0.7983565331;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.9035050869;   p1.a2 = -1.4417548180;   p1.a3 = 3.1193819046;
p1.c1a = -0.0627846718; p1.c1b = 0.0916891247; p1.c1c = -11.2929878235;
p1.c2a = 0.5893976092; p1.c2b = 2.6321387291; p1.c2c = 0.3781377077;
p1.c3a = -0.1994332075; p1.c3b = 0.1371390522; p1.c3c = -48.0305595398;
p1.L = 85.6565246582;     p1.k = 5.2521691322;    p1.x0 = 3.1584956646;
p1.L1 = 1.9830468893;   p1.k1 = 3.7645204067;   p1.x01 = 0.1448555142;
p1.L2 = 0.6732512116;   p1.k2 = 13.8171854019;   p1.x02 = -1.7188792229;
p1.L3 = 0.7589492202;   p1.k3 = 4.5074596405;   p1.x03 = -0.5179294348;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.9271999598;   p2.a2 = -1.4267225266;   p2.a3 = 3.0681686401;
p2.c1a = -0.1251995116; p2.c1b = 0.1889679283; p2.c1c = -35.0399971008;
p2.c2a = 0.5873105526; p2.c2b = 2.6234626770; p2.c2c = 0.3781554997;
p2.c3a = -0.7561759949; p2.c3b = 0.2972432375; p2.c3c = -13.1053514481;
p2.L = 137.1416015625;     p2.k = 5.1376957893;    p2.x0 = 3.9979090691;
p2.L1 = 0.1581793576;   p2.k1 = 27.5805721283;   p2.x01 = -0.0459748395;
p2.L2 = 0.1180132553;   p2.k2 = 13.7964754105;   p2.x02 = -1.5651638508;
p2.L3 = 0.1206692606;   p2.k3 = 2.9529376030;   p2.x03 = -0.8256201148;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
