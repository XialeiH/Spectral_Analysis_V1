b2 = [0.5231601000, -1.1002024412, 0.3633803725];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.5081664324;   p0.a2 = -2.2282881737;   p0.a3 = 2.7948260307;
