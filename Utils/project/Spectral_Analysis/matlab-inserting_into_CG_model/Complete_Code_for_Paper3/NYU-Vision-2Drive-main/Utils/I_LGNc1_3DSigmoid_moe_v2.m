if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25493.1347656250, 19137.2363281250, 18.9547462463];
sd = [13488.2246093750, 8230.7304687500, 11.0807323456];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  -0.6466054916, 0.1985228360, -0.2112027109;
  2.3360850811, -1.4896717072, 0.5123197436;
  1.4272319078, -1.8415148258, 0.2337892652;
  2.5001771450, -1.5857186317, 0.4832949936;
  -2.1655282974, 2.2751286030, -0.4686301947;
  -1.1386024952, 1.0927869081, -0.1927414387;
  -0.8016040921, 1.4916172028, -0.1099480242;
  -0.2983541191, 0.4044907987, 0.0357016400;
  -1.6825993061, 2.3532819748, -0.2098298967;
  2.9380888939, -1.7955329418, 0.7277441025;
  2.1989576817, -2.1656551361, 0.4300799072;
  0.4292834997, 0.3712246716, 0.1802906543
