%% ================= Expert helper: forward + gradient =================
function [y, dy_dX] = eval_expert_with_grad(X, p)
% Returns:
%   y     : N x 1
%   dy_dX : N x 3  (partials wrt [x1 x2 x3])

x1 = X(:,1); x2 = X(:,2); x3 = X(:,3);
N  = size(X,1);

% base planes
base1 = 1e-4*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
base2 = 1e-4*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
base3 = 1e-4*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

dbase1 = 1e-4*[p.c1a, p.c1b, p.c1c]; % 1x3
dbase2 = 1e-4*[p.c2a, p.c2b, p.c2c];
dbase3 = 1e-4*[p.c3a, p.c3b, p.c3c];

% projections
z1 = X * p.V1.';  z2 = X * p.V2.';  z3 = X * p.V3.';

% logistic basis phi
phi1 = p.r1_L ./ (1 + exp(-p.r1_k .* (z1 - p.r1_x0)));
phi2 = p.r2_L ./ (1 + exp(-p.r2_k .* (z2 - p.r2_x0)));
phi3 = p.r3_L ./ (1 + exp(-p.r3_k .* (z3 - p.r3_x0)));

dphi1_dz = p.r1_k .* phi1 .* (1 - phi1./p.r1_L);
dphi2_dz = p.r2_k .* phi2 .* (1 - phi2./p.r2_L);
dphi3_dz = p.r3_k .* phi3 .* (1 - phi3./p.r3_L);

% r_i
r1 = base1 + phi1 * p.u1.';
r2 = base2 + phi2 * p.u2.';
r3 = base3 + phi3 * p.u3.';

% dr_i/dX  (N x 3)
dr1 = repmat(dbase1, N, 1) + (dphi1_dz .* repmat(p.u1, N, 1)) * p.V1;
dr2 = repmat(dbase2, N, 1) + (dphi2_dz .* repmat(p.u2, N, 1)) * p.V2;
dr3 = repmat(dbase3, N, 1) + (dphi3_dz .* repmat(p.u3, N, 1)) * p.V3;

% inner sigmoids b_i
b1 = p.L1 ./ (1 + exp(-p.k1 .* (r1 - p.x01)));
b2 = p.L2 ./ (1 + exp(-p.k2 .* (r2 - p.x02)));
b3 = p.L3 ./ (1 + exp(-p.k3 .* (r3 - p.x03)));

db1_dr1 = p.k1 .* b1 .* (1 - b1./p.L1);
db2_dr2 = p.k2 .* b2 .* (1 - b2./p.L2);
db3_dr3 = p.k3 .* b3 .* (1 - b3./p.L3);

db1 = dr1 .* db1_dr1;
db2 = dr2 .* db2_dr2;
db3 = dr3 .* db3_dr3;

% structured drive h
h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;

% dh/dX
dh = zeros(N,3);
dh(:,1) = 0.001*p.a1.*(1+b1) + 0.001*p.a1.*x1.*db1(:,1) + 0.001*p.a2.*x2.*db2(:,1) + 0.1*p.a3.*x3.*db3(:,1);
dh(:,2) = 0.001*p.a2.*(1+b2) + 0.001*p.a1.*x1.*db1(:,2) + 0.001*p.a2.*x2.*db2(:,2) + 0.1*p.a3.*x3.*db3(:,2);
dh(:,3) = 0.1*p.a3.*(1+b3) + 0.001*p.a1.*x1.*db1(:,3) + 0.001*p.a2.*x2.*db2(:,3) + 0.1*p.a3.*x3.*db3(:,3);

% outer sigmoid output
y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
dy_dh = 0.1*p.k .* y .* (1 - y./p.L);

dy_dX = dh .* dy_dh;
end
