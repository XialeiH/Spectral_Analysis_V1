function y = C_LGNc1_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_C_LGN1.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0071966383, -0.0061689764, 0.0364335962; ...
    -0.0048155575, -0.0033733724, -0.0624641106; ...
    0.0143386628, 0.0178821106, 0.0574130453];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.0837776661;   p0.a2 = -1.6437696218;   p0.a3 = 3.7432956696;
p0.c1a = -0.0247929320; p0.c1b = 0.1163422167; p0.c1c = -15.1033191681;
p0.c2a = 0.5853922367; p0.c2b = 2.6235127449; p0.c2c = 0.3780990243;
p0.c3a = -0.7938967943; p0.c3b = 0.4875444770; p0.c3c = -48.5709609985;
p0.L = 38.7347640991;     p0.k = 5.6519589424;    p0.x0 = 2.1295499802;
p0.L1 = 1.6418817043;   p0.k1 = 5.6669397354;   p0.x01 = 0.0799818560;
p0.L2 = 0.4914799333;   p0.k2 = 13.7969989777;   p0.x02 = -1.5746834278;
p0.L3 = 0.4518840313;   p0.k3 = 2.7581903934;   p0.x03 = -0.8350782990;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.8638056517;   p1.a2 = -1.3652172089;   p1.a3 = 2.9698677063;
p1.c1a = -0.1007093042; p1.c1b = 0.1534098685; p1.c1c = -11.4127311707;
p1.c2a = 0.5893976092; p1.c2b = 2.6321387291; p1.c2c = 0.3781377077;
p1.c3a = -0.3113062382; p1.c3b = 0.2377907485; p1.c3c = -48.2214851379;
p1.L = 84.7103652954;     p1.k = 4.6006860733;    p1.x0 = 3.2844882011;
p1.L1 = 1.9933555126;   p1.k1 = 3.9229848385;   p1.x01 = 0.1738390774;
p1.L2 = 0.5964655876;   p1.k2 = 13.8171854019;   p1.x02 = -1.7188792229;
p1.L3 = 0.6912935972;   p1.k3 = 4.8540878296;   p1.x03 = -0.3699135780;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.9406399727;   p2.a2 = -1.4366669655;   p2.a3 = 3.1320371628;
p2.c1a = -0.1236306801; p2.c1b = 0.1867119074; p2.c1c = -35.0552825928;
p2.c2a = 0.5873105526; p2.c2b = 2.6234626770; p2.c2c = 0.3781554997;
p2.c3a = -0.6988716722; p2.c3b = 0.1892138720; p2.c3c = -12.1436386108;
p2.L = 137.8982543945;     p2.k = 5.0265932083;    p2.x0 = 4.0973758698;
p2.L1 = 0.1588748693;   p2.k1 = 27.6457118988;   p2.x01 = -0.0460938141;
p2.L2 = 0.1277727783;   p2.k2 = 13.7964754105;   p2.x02 = -1.5651638508;
p2.L3 = 0.1160373092;   p2.k3 = 2.9316098690;   p2.x03 = -0.8885632157;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
