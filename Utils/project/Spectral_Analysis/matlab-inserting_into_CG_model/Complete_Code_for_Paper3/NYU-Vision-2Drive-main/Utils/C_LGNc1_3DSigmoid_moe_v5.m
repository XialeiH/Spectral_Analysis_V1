function y = eval_expert(X, p)
    x1 = X(:,1); x2 = X(:,2); x3 = X(:,3);
    base1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    base2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    base3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    Xn = (X - p.in_mu) ./ p.in_sd;
    z1 = min(max(Xn * p.V1.', -10), 10);
    z2 = min(max(Xn * p.V2.', -10), 10);
    z3 = min(max(Xn * p.V3.', -10), 10);

    phi1 = tanh(z1);
    phi2 = tanh(z2);
    phi3 = tanh(z3);

    r1 = base1 + phi1 * p.u1.';
    r2 = base2 + phi2 * p.u2.';
    r3 = base3 + phi3 * p.u3.';

    b1 = p.L1 ./ (1 + exp(-p.k1 .* (r1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2 .* (r2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3 .* (r3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
