function y = eval_expert(x1, x2, x3, p)
    b1_lin = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2_lin = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3_lin = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    % Piecewise-linear hidden units (ReLU shifted by x0, scaled by k and L)
    b1 = max(0, p.k1 .* (b1_lin - p.x01)) .* p.L1;
    b2 = max(0, p.k2 .* (b2_lin - p.x02)) .* p.L2;
    b3 = max(0, p.k3 .* (b3_lin - p.x03)) .* p.L3;

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end