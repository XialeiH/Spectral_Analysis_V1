function y = S_LGNc1_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_S_LGN1.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0070736050, -0.0055464329, 0.0269614644; ...
    -0.0204592068, 0.0002292586, -0.0492482446; ...
    0.0237174351, 0.0167581122, -0.0084994184];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.7392718196;   p0.a2 = -1.7128603458;   p0.a3 = 2.8368275166;
p0.c1a = -0.9909049869; p0.c1b = 1.4669656754; p0.c1c = -21.6370029449;
p0.c2a = 0.5119140744; p0.c2b = 2.5268001556; p0.c2c = 0.2867530584;
p0.c3a = -2.5116267204; p0.c3b = 0.7705189586; p0.c3c = -14.6876821518;
p0.L = 37.8346710205;     p0.k = 4.1871633530;    p0.x0 = -1.6664565802;
p0.L1 = 0.6497603655;   p0.k1 = 0.7495602965;   p0.x01 = 0.6138046980;
p0.L2 = 0.2611853778;   p0.k2 = 13.6477403641;   p0.x02 = -1.4349496365;
p0.L3 = 0.2557582855;   p0.k3 = 0.6207858920;   p0.x03 = -2.4774224758;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 1.2048395872;   p1.a2 = -1.7685966492;   p1.a3 = 2.9926540852;
p1.c1a = 0.0107030505; p1.c1b = 1.3131500483; p1.c1c = -30.4691181183;
p1.c2a = 0.5147938728; p1.c2b = 2.5326433182; p1.c2c = 0.2867530584;
p1.c3a = -1.6232509613; p1.c3b = 2.3718056679; p1.c3c = -19.9769706726;
p1.L = 69.1912612915;     p1.k = 4.4717378616;    p1.x0 = 0.4857604206;
p1.L1 = 1.8705334663;   p1.k1 = 1.7079192400;   p1.x01 = 0.4108000398;
p1.L2 = 0.2583760023;   p1.k2 = 13.6585683823;   p1.x02 = -1.5207278728;
p1.L3 = 0.3369369209;   p1.k3 = 0.6293636560;   p1.x03 = -1.7686175108;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.7019977570;   p2.a2 = -1.6323820353;   p2.a3 = 2.7108836174;
p2.c1a = -0.1756642014; p2.c1b = 0.3156200349; p2.c1c = -38.3275566101;
p2.c2a = 0.5194622874; p2.c2b = 2.5365171432; p2.c2c = 0.2867960036;
p2.c3a = -1.6490911245; p2.c3b = -0.3356091082; p2.c3c = -24.8339481354;
p2.L = 127.5798645020;     p2.k = 3.7289335728;    p2.x0 = 2.7909200191;
p2.L1 = 1.4320241213;   p2.k1 = 2.3293545246;   p2.x01 = 0.7147228718;
p2.L2 = 0.0822747871;   p2.k2 = 13.6706399918;   p2.x02 = -1.5902957916;
p2.L3 = 0.1902935207;   p2.k3 = 0.5604927540;   p2.x03 = -3.7403783798;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
