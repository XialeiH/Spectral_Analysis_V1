    base1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    base2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    base3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    z1 = X * p.V1.';  z2 = X * p.V2.';  z3 = X * p.V3.';
