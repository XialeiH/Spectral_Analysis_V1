function y = S_LGNc2_3DSigmoid_moe_v2(L4EUse, L4IUse, L6Use) %#codegen
% MoE v2 sigmoid generated from moe_S_LGN2_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25045.0195312500, 15954.5810546875, 21.3637828827];
sd = [13344.8193359375, 7343.1582031250, 11.1932296753];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  0.8084668517, -1.5041192770, 0.5639601350;
  -1.0310819149, 1.1274584532, 0.0228929706;
  1.2447640896, -2.1659231186, 0.5336040854;
  -0.6033796668, 0.7226468325, -0.1575589925;
  -0.1198471040, -0.4084418118, 0.1467016637;
  1.2890770435, -2.4457583427, 0.7723678350;
  -0.6886287332, -0.7275427580, -0.9412289262;
  1.3558281660, -1.8012260199, 0.4410193861;
  0.0087710135, 1.1423125267, 0.0831000730;
  -0.4976227283, -0.6377713084, 0.2557492852;
  -0.7461736798, 0.3432679474, -0.6518370509;
  0.9499949217, 0.7632514834, -0.7699120641
];
b1 = [-0.4913733006, 0.0471212640, -0.9114678502, -0.0939175934, 1.7431792021, -0.8624131083, -0.0901716053, 0.6039152741, 1.8643085957, -0.5464815497, -0.1226734966, 3.7969973087];
h = tanh(xg * W1.' + b1);

% Gate fc2 -> logits
W2 = [
  -0.9546975493, 0.8967206478, -1.0337498188, 0.4248565435, 0.3498704731, -1.1673042774, 1.2459348440, -1.0473129749, -2.5748677254, 0.9612951875, 1.4784100056, -2.8446679115;
  -0.0176907349, 0.0651765615, -0.5237054229, 0.0895224214, -0.3442033529, -0.1000881642, -0.8014475703, -0.0530428700, 0.4282557666, 0.0066244965, -0.1649029106, 2.2871587276;
  0.6942462921, -0.7086031437, 0.8057002425, -0.4706259370, 0.1599315852, 0.7053396106, -0.2056728750, 0.6476452947, 1.5146813393, -0.9736950994, -1.1563057899, 1.5573772192
];
b2 = [0.6000813246, 0.0629146472, -0.2294142693];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.9384072423;   p0.a2 = -1.8351193666;   p0.a3 = 2.9767880440;
