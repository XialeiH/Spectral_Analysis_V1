p0.L2 = 0.5749656558;   p0.k2 = 13.6477403641;   p0.x02 = -1.4415935278;
p0.L3 = 0.7213653922;   p0.k3 = 0.3686282039;   p0.x03 = -2.9888904095;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.8151125908;   p1.a2 = -1.7576184273;   p1.a3 = 2.9999699593;
