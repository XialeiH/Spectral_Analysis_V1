function y = C_LGNc5_3DSigmoid_moe_v2(L4EUse, L4IUse, L6Use) %#codegen
% MoE v2 sigmoid generated from moe_C_LGN5_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25272.3847656250, 18045.9863281250, 18.2035751343];
sd = [13462.4775390625, 8440.6591796875, 10.8856754303];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  0.9091473818, -0.8918529153, 0.5973897576;
  -1.3923945427, 1.7601522207, -0.3968088329;
  1.1958588362, -1.5463253260, 0.4514081776;
  1.1270978451, -0.9768903255, 0.1649897397;
  0.9699505568, -0.9061221480, 0.2188588679;
  -0.0356444791, 0.7451301813, -0.4462656975;
  1.2396535873, -1.9142304659, 0.3251959682;
  1.2971749306, -0.8213551044, 0.4059883058;
  -1.3549757004, 0.7561320662, -0.0123179676;
  1.2176709175, -1.6527532339, 0.6371431351;
  -1.2409696579, 0.9516826868, 0.0131761264;
  1.0067028999, -0.8903434873, 0.1400664747
];
b1 = [0.9134634137, 0.4159919918, -0.3191412985, -0.1698210239, -0.0079019954, 0.2810122967, -1.1178331375, 0.1139229387, -0.9091266394, -0.2940533161, 0.3758540750, 0.2100374997];
h = tanh(xg * W1.' + b1);

% Gate fc2 -> logits
W2 = [
  -0.2490000725, 1.2344888449, -1.2152090073, -1.0999574661, -0.7059412599, 0.6549701691, -1.6372107267, -1.1321766376, 0.5656013489, -1.2119820118, 1.2313613892, -0.7593923211;
  0.5971544981, 0.3073754907, -0.3948103189, -0.7774459124, -0.5525999069, -0.2670515180, -0.1829177886, -0.5468686223, -0.9336132407, -0.0071501657, -0.1007592827, 0.3647720218;
  0.0886249393, -1.1329582930, 1.1407939196, 1.1696999073, 0.8056855202, -0.6158996224, 1.4073613882, 1.1187353134, -0.1075639352, 1.0642758608, -1.0931899548, 0.5924158096
];
b2 = [0.1490283012, 0.1751719415, -0.0562442876];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.0399073362;   p0.a2 = -1.5805789232;   p0.a3 = 3.5506618023;
p0.c1a = -0.1056067273; p0.c1b = 0.1393292695; p0.c1c = -15.7806024551;
