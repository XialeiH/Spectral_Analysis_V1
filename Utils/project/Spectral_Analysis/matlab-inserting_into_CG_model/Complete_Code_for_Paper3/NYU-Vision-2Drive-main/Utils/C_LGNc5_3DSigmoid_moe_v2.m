p0.L3 = 0.4552442729;   p0.k3 = 1.7114121914;   p0.x03 = -1.4543768167;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.9197932482;   p1.a2 = -1.4643169641;   p1.a3 = 3.2804074287;
