p0.c3a = -1.0526335239; p0.c3b = 0.2664746940; p0.c3c = -34.8968658447;
p0.L = 33.7804832458;     p0.k = 6.0509114265;    p0.x0 = 2.7102763653;
p0.L1 = 1.5127059221;   p0.k1 = 6.6501712799;   p0.x01 = 0.0723812208;
