function y = I_LGNc5_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_I_LGN5.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0114363441, -0.0103485323, -0.0467950478; ...
    -0.0002628693, 0.0016379504, 0.0438628644; ...
    0.0304309782, 0.0294431951, 0.0488158353];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.3142008781;   p0.a2 = -2.2884950638;   p0.a3 = 3.1117801666;
p0.c1a = 2.3573861122; p0.c1b = 0.1975495368; p0.c1c = 0.7409085631;
p0.c2a = 0.6164997816; p0.c2b = 2.6974699497; p0.c2c = 0.4635282457;
p0.c3a = -0.2158005834; p0.c3b = 0.2933088839; p0.c3c = -36.1281356812;
p0.L = 28.6152057648;     p0.k = 5.2395987511;    p0.x0 = -1.0875030756;
p0.L1 = 0.2139827907;   p0.k1 = 5.3563785553;   p0.x01 = 1.0939298868;
p0.L2 = 0.2798261642;   p0.k2 = 13.8994865417;   p0.x02 = -1.6441260576;
p0.L3 = 0.2098247558;   p0.k3 = 29.9619960785;   p0.x03 = -0.2430200279;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 1.3373796940;   p1.a2 = -2.2020878792;   p1.a3 = 3.0234897137;
p1.c1a = 1.7963321209; p1.c1b = 0.5459558964; p1.c1c = 0.6632635593;
p1.c2a = 0.6170958281; p1.c2b = 2.6974699497; p1.c2c = 0.4635282457;
p1.c3a = -0.2839902341; p1.c3b = 0.3797618747; p1.c3c = -36.6697769165;
p1.L = 78.0988540649;     p1.k = 4.2252435684;    p1.x0 = 0.5676183105;
p1.L1 = 0.1805909872;   p1.k1 = 4.0760812759;   p1.x01 = 1.2120648623;
p1.L2 = 0.1652986407;   p1.k2 = 13.8994865417;   p1.x02 = -1.6536628008;
p1.L3 = 0.1995651126;   p1.k3 = 30.2666664124;   p1.x03 = -0.1939447522;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 1.2288553715;   p2.a2 = -2.2446646690;   p2.a3 = 2.5177402496;
p2.c1a = 1.8007968664; p2.c1b = -0.9611778855; p2.c1c = 5.7119040489;
p2.c2a = 0.6179384589; p2.c2b = 2.6998541355; p2.c2c = 0.4635282457;
p2.c3a = -0.2547345161; p2.c3b = 0.3516923189; p2.c3c = -37.1368255615;
p2.L = 134.3009338379;     p2.k = 4.2033653259;    p2.x0 = 2.6308293343;
p2.L1 = 0.2511640787;   p2.k1 = 7.2991313934;   p2.x01 = 0.0918988362;
p2.L2 = 0.1232099831;   p2.k2 = 13.8999538422;   p2.x02 = -1.6710052490;
p2.L3 = 0.4497942626;   p2.k3 = 28.6800975800;   p2.x03 = -0.1613555104;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
