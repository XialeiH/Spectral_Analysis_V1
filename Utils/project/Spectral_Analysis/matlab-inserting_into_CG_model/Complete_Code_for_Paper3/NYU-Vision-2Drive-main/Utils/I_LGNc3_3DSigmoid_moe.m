function y = I_LGNc3_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_I_LGN3.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0085551655, -0.0051447665, -0.0362793803; ...
    -0.0242634863, -0.0080217859, -0.0071841138; ...
    0.0431837402, 0.0519835949, 0.0639877617];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.2371329069;   p0.a2 = -2.1148149967;   p0.a3 = 2.9666621685;
p0.c1a = 3.3332748413; p0.c1b = -0.7394253612; p0.c1c = 0.0415972993;
p0.c2a = 0.6164760590; p0.c2b = 2.6974699497; p0.c2c = 0.4635282457;
p0.c3a = 2.2468588352; p0.c3b = 1.0228035450; p0.c3c = 1.1066236496;
p0.L = 28.6987400055;     p0.k = 5.6793208122;    p0.x0 = -2.6530134678;
p0.L1 = 0.0327923857;   p0.k1 = 9.0878000259;   p0.x01 = 1.6470713615;
p0.L2 = 0.0923154578;   p0.k2 = 13.8994865417;   p0.x02 = -1.6369854212;
p0.L3 = 0.0618980117;   p0.k3 = 6.6674466133;   p0.x03 = 1.6557621956;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 1.2549471855;   p1.a2 = -2.1700694561;   p1.a3 = 2.7160549164;
p1.c1a = 1.9623913765; p1.c1b = -0.1017200574; p1.c1c = 0.3251181245;
p1.c2a = 0.6164760590; p1.c2b = 2.6974699497; p1.c2c = 0.4635282457;
p1.c3a = 2.1999855042; p1.c3b = 0.9183338284; p1.c3c = 1.2406048775;
p1.L = 77.1312408447;     p1.k = 4.4733147621;    p1.x0 = -0.8221430182;
p1.L1 = 0.0433048494;   p1.k1 = 9.0779504776;   p1.x01 = 1.3275353909;
p1.L2 = 0.1219421849;   p1.k2 = 13.8994865417;   p1.x02 = -1.6381775141;
p1.L3 = 0.0899825320;   p1.k3 = 6.8371682167;   p1.x03 = 1.3276759386;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 1.1235295534;   p2.a2 = -2.2471337318;   p2.a3 = 2.5506532192;
p2.c1a = 0.5932056308; p2.c1b = -0.3057939708; p2.c1c = 7.4818501472;
p2.c2a = 0.6170667410; p2.c2b = 2.6974699497; p2.c2c = 0.4635282457;
p2.c3a = 3.0155596733; p2.c3b = -0.0679426864; p2.c3c = 7.4006385803;
p2.L = 126.3540496826;     p2.k = 3.7827353477;    p2.x0 = -0.3342127800;
p2.L1 = 0.3861627281;   p2.k1 = 15.4697284698;   p2.x01 = 0.0470901877;
p2.L2 = 0.1688546389;   p2.k2 = 13.8994865417;   p2.x02 = -1.6503574848;
p2.L3 = 0.4288330376;   p2.k3 = 10.5308122635;   p2.x03 = 0.0666114390;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
