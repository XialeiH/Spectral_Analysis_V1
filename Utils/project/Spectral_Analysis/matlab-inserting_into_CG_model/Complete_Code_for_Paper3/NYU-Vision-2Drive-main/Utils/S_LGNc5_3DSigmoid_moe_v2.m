% Gate fc2 -> logits
W2 = [
  -0.9426884055, -3.2192292213, 0.8976525068, 2.5442297459, 1.4904001951, -1.5905506611, -1.7448555231, 0.9360379577, 1.2561823130, -1.4287164211, -0.9701604247, 0.9545550942;
  0.2408601642, 1.2630482912, 0.2723840475, -0.4781625271, -1.1024297476, 0.1096873209, 2.1856966019, 0.1362049282, 0.3030789793, -0.9578139186, -0.5815911293, 0.7940649986;
  0.6671574712, 1.7061508894, -0.6819952130, -0.8582931757, 0.0469103642, 0.9569899440, 0.6442863345, -0.6682235599, -0.9612501860, 1.9253536463, 0.8300110698, -0.8964920044
];
b2 = [1.2884501219, -0.2311703712, -0.2091691941];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.8298051357;   p0.a2 = -1.9866709709;   p0.a3 = 3.0035994053;
