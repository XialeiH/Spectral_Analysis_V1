% MoE v2 sigmoid generated from moe_S_LGN5_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [24638.2871093750, 15033.1601562500, 22.2841892242];
sd = [13260.1230468750, 7291.1816406250, 11.1284542084];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  0.6726943851, -1.8135607243, 1.3066756725;
  0.6626064181, 1.4753125906, -0.4842394590;
  -1.3389490843, 2.0276556015, -0.5904467106;
  -0.5139701962, -0.9493687153, 0.1192993447;
  -1.4775937796, 2.2810177803, -1.1131386757;
  0.2655479014, 1.5541955233, -0.8520165086;
  1.4139794111, 0.0533940680, -0.1915691197;
  -1.2365148067, 1.8924341202, -0.5849602818;
  -1.0898051262, 2.3051984310, -0.8363439441;
  0.8716375232, 0.0744335279, 0.2249705046;
  1.1033890247, -1.5531032085, 0.5373920202;
  -1.3244596720, 2.5634319782, -0.5408026576
];
