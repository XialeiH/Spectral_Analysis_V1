function y = S_LGNc5_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_S_LGN5.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    0.0003703578, 0.0008729778, -0.0315809883; ...
    -0.0013444979, 0.0001033765, 0.0342401713; ...
    0.0170901548, 0.0165368188, 0.0204180777];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.8054548502;   p0.a2 = -1.8208652735;   p0.a3 = 3.1102752686;
p0.c1a = -0.2762657106; p0.c1b = 0.3809063137; p0.c1c = -31.6510429382;
p0.c2a = 0.5129422545; p0.c2b = 2.5291843414; p0.c2c = 0.2867530584;
p0.c3a = -2.2999451160; p0.c3b = 1.4437021017; p0.c3c = -22.5848865509;
p0.L = 31.8115081787;     p0.k = 5.3272571564;    p0.x0 = 0.6949501634;
p0.L1 = 1.6453996897;   p0.k1 = 2.0155096054;   p0.x01 = 0.3938648701;
p0.L2 = 0.5661399364;   p0.k2 = 13.6477403641;   p0.x02 = -1.4613487720;
p0.L3 = 0.5546500683;   p0.k3 = 0.4790668190;   p0.x03 = -2.4477910995;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.7726165056;   p1.a2 = -1.6634622812;   p1.a3 = 2.8439354897;
p1.c1a = -0.1677260846; p1.c1b = 0.3854623139; p1.c1c = -36.4996223450;
p1.c2a = 0.5195961595; p1.c2b = 2.5370004177; p1.c2c = 0.2867530584;
p1.c3a = -1.1377381086; p1.c3b = -0.2877761424; p1.c3c = -27.5208930969;
p1.L = 70.1519012451;     p1.k = 4.8588504791;    p1.x0 = 1.7549139261;
p1.L1 = 1.6628184319;   p1.k1 = 2.3188073635;   p1.x01 = 0.7495327592;
p1.L2 = 0.2561190128;   p1.k2 = 13.6689491272;   p1.x02 = -1.5961987972;
p1.L3 = 0.2087836117;   p1.k3 = 1.2037111521;   p1.x03 = -4.7583408356;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.5794227719;   p2.a2 = -1.5622411966;   p2.a3 = 2.7259192467;
p2.c1a = -0.1165148169; p2.c1b = 0.2303349078; p2.c1c = -45.1752319336;
p2.c2a = 0.5214424133; p2.c2b = 2.5388717651; p2.c2c = 0.2867960036;
p2.c3a = 0.4825761318; p2.c3b = -1.8545002937; p2.c3c = -31.4607467651;
p2.L = 128.2570190430;     p2.k = 4.7945771217;    p2.x0 = 4.3237566948;
p2.L1 = 1.9493664503;   p2.k1 = 3.2530086040;   p2.x01 = 0.3284548819;
p2.L2 = 0.1309899241;   p2.k2 = 13.6713209152;   p2.x02 = -1.6197198629;
p2.L3 = 0.1458094120;   p2.k3 = 3.2633755207;   p2.x03 = -4.2475242615;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
