function y = S_LGNc2_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_S_LGN2.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0055062845, -0.0033795661, 0.0698188543; ...
    -0.0062796962, -0.0056637130, -0.0570466332; ...
    0.0145265004, 0.0174301434, 0.0503267832];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.8124223351;   p0.a2 = -1.7525234222;   p0.a3 = 3.0142924786;
p0.c1a = -0.2513276935; p0.c1b = 0.4304647744; p0.c1c = -31.8339462280;
p0.c2a = 0.5119140744; p0.c2b = 2.5268001556; p0.c2c = 0.2867530584;
p0.c3a = -1.7907971144; p0.c3b = 0.0325537920; p0.c3c = -28.7889919281;
p0.L = 38.1811752319;     p0.k = 5.0259199142;    p0.x0 = -0.7721481919;
p0.L1 = 1.7779424191;   p0.k1 = 1.9227840900;   p0.x01 = 0.6300984621;
p0.L2 = 0.4929834902;   p0.k2 = 13.6477403641;   p0.x02 = -1.4415935278;
p0.L3 = 0.7621086836;   p0.k3 = 0.4151481986;   p0.x03 = -3.0255985260;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.8097633719;   p1.a2 = -1.7538086176;   p1.a3 = 2.9942867756;
p1.c1a = -0.2020267844; p1.c1b = 0.4166457951; p1.c1c = -36.2571868896;
p1.c2a = 0.5163722038; p1.c2b = 2.5364601612; p1.c2c = 0.2867530584;
p1.c3a = -1.9157384634; p1.c3b = 0.9081615210; p1.c3c = -27.9638233185;
p1.L = 76.6190719604;     p1.k = 4.2083678246;    p1.x0 = 0.3528193235;
p1.L1 = 1.6479852200;   p1.k1 = 1.9362952709;   p1.x01 = 0.6337292790;
p1.L2 = 0.3425398469;   p1.k2 = 13.6681051254;   p1.x02 = -1.5808093548;
p1.L3 = 0.3816313148;   p1.k3 = 0.5084555149;   p1.x03 = -3.5598466396;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.7056709528;   p2.a2 = -1.7228171825;   p2.a3 = 2.9268193245;
p2.c1a = -0.1666276753; p2.c1b = 0.3241547942; p2.c1c = -40.1798744202;
p2.c2a = 0.5207703710; p2.c2b = 2.5377092361; p2.c2c = 0.2867960036;
p2.c3a = -1.2015359402; p2.c3b = -0.9943972230; p2.c3c = -27.2679462433;
p2.L = 129.3070373535;     p2.k = 3.9837586880;    p2.x0 = 2.9876008034;
p2.L1 = 1.6138131618;   p2.k1 = 2.3766822815;   p2.x01 = 0.5463218093;
p2.L2 = 0.1433005631;   p2.k2 = 13.6754083633;   p2.x02 = -1.6123571396;
p2.L3 = 0.2309558839;   p2.k3 = 0.4935203195;   p2.x03 = -3.9632151127;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
