if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25165.1464843750, 18170.1250000000, 17.8857212067];
sd = [13497.5400390625, 8433.7871093750, 10.8320798874];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  -0.0980510414, -0.1526253372, -0.5852891207;
  -0.7366162539, 0.4001322091, -0.1383876354;
  -1.1733019352, 0.6476009488, -0.0219431985;
  0.4955692887, 0.0031756291, 0.1802867502;
