function y = C_LGNc5_3DSigmoid_moe(L4EUse, L4IUse, L6Use) %#codegen
% Mixture-of-experts sigmoid generated from moe_C_LGN5.pt
% Uses softmax gating over three experts trained in PyTorch.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate weights (rows = expert logits)
W = [...
    -0.0103549035, -0.0082413955, 0.0341680534; ...
    -0.0246780887, -0.0006667380, 0.0089314505; ...
    0.0448782332, 0.0282514989, -0.0116543509];

logits = (W * [x1.'; x2.'; x3.']).';
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 0.8022294044;   p0.a2 = -1.6545165777;   p0.a3 = 3.6130282879;
p0.c1a = -0.1641877741; p0.c1b = 0.0280842818; p0.c1c = -15.6194133759;
p0.c2a = 0.5893293023; p0.c2b = 2.6320049763; p0.c2c = 0.3780990243;
p0.c3a = -0.9510073066; p0.c3b = 0.3820116520; p0.c3c = -34.6005249023;
p0.L = 33.8575820923;     p0.k = 6.1906461716;    p0.x0 = 2.7168903351;
p0.L1 = 1.2671676874;   p0.k1 = 6.6543359756;   p0.x01 = 0.2806999385;
p0.L2 = 0.5117219687;   p0.k2 = 13.8145494461;   p0.x02 = -1.6902718544;
p0.L3 = 0.3274432123;   p0.k3 = 1.7903654575;   p0.x03 = -1.5271282196;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 0.9441388845;   p1.a2 = -1.4011186361;   p1.a3 = 3.1339619160;
p1.c1a = -0.0228622649; p1.c1b = 0.1935644150; p1.c1c = -18.5775318146;
p1.c2a = 0.5921487212; p1.c2b = 2.6311733723; p1.c2c = 0.3780990243;
p1.c3a = -0.9339922071; p1.c3b = -0.0937867016; p1.c3c = -26.4710254669;
p1.L = 78.8759307861;     p1.k = 5.8174695969;    p1.x0 = 3.4827828407;
p1.L1 = 1.2147613764;   p1.k1 = 7.8058075905;   p1.x01 = 0.0573523492;
p1.L2 = 0.2261316776;   p1.k2 = 13.8144750595;   p1.x02 = -1.6818717718;
p1.L3 = 0.2580923140;   p1.k3 = 1.1054763794;   p1.x03 = -2.1034410000;

y1 = eval_expert(x1, x2, x3, p1);

% Expert 2 params
p2.a1 = 0.9852688313;   p2.a2 = -1.4914144278;   p2.a3 = 2.9463517666;
p2.c1a = -0.0641428307; p2.c1b = 0.0972777084; p2.c1c = -24.1209087372;
p2.c2a = 0.6123423576; p2.c2b = 2.7010326385; p2.c2c = 0.3783640862;
p2.c3a = 5.0049419403; p2.c3b = 0.3795535862; p2.c3c = -21.3977336884;
p2.L = 121.7825622559;     p2.k = 4.4614124298;    p2.x0 = 4.9462590218;
p2.L1 = 0.6334239841;   p2.k1 = 12.9926900864;   p2.x01 = 0.0125528518;
p2.L2 = 0.3091035783;   p2.k2 = 13.9404878616;   p2.x02 = -2.0276966095;
p2.L3 = 0.4236698449;   p2.k3 = 13.5491571426;   p2.x03 = 0.0866148546;

y2 = eval_expert(x1, x2, x3, p2);


y = pis(:,1).*y0 + pis(:,2).*y1 + pis(:,3).*y2;
y = reshape(y, origSize);
end


function y = eval_expert(x1, x2, x3, p)
    b1 = 0.0001*(p.c1a.*x1 + p.c1b.*x2 + p.c1c.*x3);
    b2 = 0.0001*(p.c2a.*x1 + p.c2b.*x2 + p.c2c.*x3);
    b3 = 0.0001*(p.c3a.*x1 + p.c3b.*x2 + p.c3c.*x3);

    b1 = p.L1 ./ (1 + exp(-p.k1.*(b1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2.*(b2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3.*(b3 - p.x03)));

    h = 0.001*p.a1.*(1+b1).*x1 + 0.001*p.a2.*(1+b2).*x2 + 0.1*p.a3.*(1+b3).*x3;
    y = p.L ./ (1 + exp(-p.k*0.1.*(h - p.x0)));
end
