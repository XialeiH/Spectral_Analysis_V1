function y = I_LGNc2_3DSigmoid_moe_v2(L4EUse, L4IUse, L6Use) %#codegen
% MoE v2 sigmoid generated from moe_I_LGN2_v2.pt
% Deep gate (tanh hidden) + softmax over three experts.

origSize = size(L4EUse);
if ~isequal(size(L4EUse), size(L4IUse), size(L6Use))
    error('Inputs must have the same shape.');
end

x1 = L4EUse(:);
x2 = L4IUse(:);
x3 = L6Use(:);

% Gate normalization
mu = [25494.6777343750, 19138.3105468750, 18.9528751373];
sd = [13488.2744140625, 8230.8476562500, 11.0808992386];
xg = [(x1-mu(1))./sd(1), (x2-mu(2))./sd(2), (x3-mu(3))./sd(3)];

% Gate fc1 (hidden tanh)
W1 = [
  -1.5766996145, 1.6036732197, -0.3142630756;
  -0.0253961347, -0.6032530069, 0.2203288376;
  -2.5978918076, 1.9460204840, -0.7853342891;
  -0.4393776357, -0.0508165620, 0.0621789061;
  -1.4429299831, 1.4911899567, -0.2783707082;
  0.3535342216, -0.0776283145, 0.2650978267;
  1.5804262161, -1.5969903469, 0.1966238618;
  0.9693697691, -1.9934283495, 0.2168076783;
  -1.9834707975, 2.5514986515, -0.2996265292;
  2.8415007591, -1.8052788973, 0.4439870119;
  -2.1605432034, 2.2478289604, -0.4164016247;
  0.9272655249, -0.1974644661, 0.2380062342
];
b1 = [0.9254603982, -1.3314652443, -2.1072494984, -1.2616094351, 0.8984973431, -0.1540721655, -0.7395476699, 2.0037713051, 1.7957743406, 2.3139052391, 1.1701591015, -0.3664896786];
h = tanh(xg * W1.' + b1);

% Gate fc2 -> logits
W2 = [
  1.2574285269, -0.0537578762, 1.9995082617, -0.1009338275, 1.3094087839, -0.2363727391, -1.2612557411, -0.0805029646, 1.4291628599, -1.9848783016, 1.3300821781, 0.5906200409;
  0.5480382442, -0.6946536303, -1.4565026760, 0.8584389091, 0.3545846641, -0.3937829733, -0.0173217729, -1.1476920843, 1.2380332947, 1.2152987719, 1.3358509541, -0.1862621009;
  -1.0631177425, 0.4347832501, -1.7883294821, -1.2012559175, -1.1776083708, 0.2790337503, 1.1420170069, 1.3224190474, -1.5199646950, 1.9819235802, -1.6749809980, -0.8729419112
];
b2 = [0.3672713935, -0.9119238257, 0.3116309941];
logits = h * W2.' + b2;
logits = logits - max(logits, [], 2);
pis = exp(logits);
pis = pis ./ sum(pis, 2);

% Expert 0 params
p0.a1 = 1.5287369490;   p0.a2 = -2.2420599461;   p0.a3 = 2.7690787315;
p0.c1a = 3.3915328979; p0.c1b = -0.6721289158; p0.c1c = 0.0630898103;
p0.c2a = 0.6164760590; p0.c2b = 2.6974699497; p0.c2c = 0.4635282457;
p0.c3a = 2.4938600063; p0.c3b = 1.2685159445; p0.c3c = 1.3530536890;
p0.L = 28.2979316711;     p0.k = 6.0157403946;    p0.x0 = -2.3717100620;
p0.L1 = 0.2065595090;   p0.k1 = 8.4351873398;   p0.x01 = 1.4998672009;
p0.L2 = 0.2140278965;   p0.k2 = 13.8994865417;   p0.x02 = -1.6369854212;
p0.L3 = 0.2864398956;   p0.k3 = 6.5514855385;   p0.x03 = 1.3670916557;

y0 = eval_expert(x1, x2, x3, p0);

% Expert 1 params
p1.a1 = 1.2283945084;   p1.a2 = -2.0635566711;   p1.a3 = 2.8202717304;
p1.c1a = 1.5855370760; p1.c1b = -0.3296250999; p1.c1c = 0.4857529700;
p1.c2a = 0.6164760590; p1.c2b = 2.6974699497; p1.c2c = 0.4635282457;
p1.c3a = 2.3097476959; p1.c3b = 1.0503749847; p1.c3c = 1.4025537968;
p1.L = 78.4004135132;     p1.k = 4.1601796150;    p1.x0 = -1.3716827631;
p1.L1 = 0.0158394501;   p1.k1 = 8.4304475784;   p1.x01 = 1.6446485519;
p1.L2 = 0.0165468995;   p1.k2 = 13.8994865417;   p1.x02 = -1.6381775141;
p1.L3 = -0.0051799403;   p1.k3 = 6.6759142876;   p1.x03 = 1.1729063988;

