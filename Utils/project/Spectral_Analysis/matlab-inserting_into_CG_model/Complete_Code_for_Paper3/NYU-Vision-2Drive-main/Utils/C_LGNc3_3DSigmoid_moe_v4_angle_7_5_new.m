    phi2 = p.r2_L ./ (1 + exp(-p.r2_k .* (z2 - p.r2_x0)));
    phi3 = p.r3_L ./ (1 + exp(-p.r3_k .* (z3 - p.r3_x0)));

    r1 = base1 + phi1 * p.u1.';
    r2 = base2 + phi2 * p.u2.';
    r3 = base3 + phi3 * p.u3.';

    b1 = p.L1 ./ (1 + exp(-p.k1 .* (r1 - p.x01)));
    b2 = p.L2 ./ (1 + exp(-p.k2 .* (r2 - p.x02)));
    b3 = p.L3 ./ (1 + exp(-p.k3 .* (r3 - p.x03)));

