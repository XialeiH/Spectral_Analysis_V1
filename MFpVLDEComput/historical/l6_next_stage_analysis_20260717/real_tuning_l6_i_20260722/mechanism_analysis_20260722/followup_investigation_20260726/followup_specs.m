function specs = followup_specs(kind)
% Parameter grids for branch, sensitivity, interpolation, and threshold tasks.

switch lower(kind)
    case 'branch'
        l6 = [0.15 0.16 0.168 0.169 0.1698 0.17 0.1702 0.171 ...
            0.175 0.18 0.20 0.24 0.275 0.30 0.35]';
        inh = [-0.12 -0.11 -0.10 -0.095 -0.09 -0.085 -0.08 ...
            -0.075 -0.07 -0.065 -0.06 -0.055 -0.05]';
        specs = table((1:numel(l6)+numel(inh))', ...
            [repmat("L6",numel(l6),1);repmat("Inhibition",numel(inh),1)], ...
            [l6;inh],'VariableNames',{'taskId','pathway','beta'});
    case 'sensitivity'
        l6 = [0.15 0.17 0.20 0.25 0.275]';
        inh = [-0.05 -0.075 -0.08 -0.10]';
        specs = table((1:numel(l6)+numel(inh))', ...
            [repmat("L6",numel(l6),1);repmat("Inhibition",numel(inh),1)], ...
            [l6;inh],'VariableNames',{'taskId','pathway','beta'});
    case 'interpolation'
        specs = table((1:3)',["L6";"L6";"Inhibition"], ...
            [0.20;0.275;-0.075], ...
            'VariableNames',{'taskId','pathway','beta'});
    case 'threshold'
        scales = [0.8 0.9 1.0 1.1 1.2 NaN]';
        specs = table((1:12)', ...
            [repmat("L6",6,1);repmat("Inhibition",6,1)], ...
            [scales;scales], ...
            [repmat("extended",5,1);"raw";repmat("extended",5,1);"raw"], ...
            'VariableNames',{'taskId','pathway','edgeScale','mapMode'});
    otherwise
        error('Followup:Kind','Unknown specification kind %s.',kind);
end
end
