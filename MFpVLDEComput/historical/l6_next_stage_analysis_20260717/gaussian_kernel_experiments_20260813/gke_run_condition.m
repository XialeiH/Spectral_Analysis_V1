function summary=gke_run_condition(taskIndex,setupFile,outputRoot)
% Run one manipulation through fixed point, Jacobian, eigen, and SVD analysis.

if nargin<1 || isempty(taskIndex); taskIndex=str2double(getenv('SLURM_ARRAY_TASK_ID')); end
if nargin<2 || isempty(setupFile); setupFile=getenv('GKE_SETUP'); end
if nargin<3 || isempty(outputRoot); outputRoot=getenv('GKE_OUTPUT'); end
catalog=gke_condition_catalog();
if taskIndex<1 || taskIndex>height(catalog)
    error('GKE:Task','Task index must be between 1 and %d.',height(catalog));
end
for directory=["data" "summaries" "operator_audits"]
    path=fullfile(outputRoot,directory); if ~exist(path,'dir'); mkdir(path); end
end

loaded=load(setupFile,'setup');
setup=loaded.setup;
context=setup.Context;
condition=catalog(taskIndex,:);
[operators,metadata,operatorAudit]=gke_build_operators(context,condition.name);
writetable(operatorAudit,fullfile(outputRoot,'operator_audits',condition.name+'.tsv'), ...
    'FileType','text','Delimiter','\t');

equilibriumCache=fullfile(outputRoot,'equilibrium_only','data',condition.name+'.mat');
if isfile(equilibriumCache)
    cached=load(equilibriumCache,'fixedPoint','solver');
    fixedPoint=cached.fixedPoint;
    solver=cached.solver;
    solver.Method=solver.Method+"; reused verified equilibrium-only cache";
else
    knownFoldControls=["swap_EI_ranges" "remove_L6_smoothing"];
    [fixedPoint,solver]=gke_track_equilibrium(setup,operators, ...
        condition.name=="baseline",ismember(condition.name,knownFoldControls));
end
response=l6ns_controlled_phi(fixedPoint,context,operators);
fixedPointResidual=norm(response-fixedPoint)/max(norm(fixedPoint),eps);
if ~solver.Converged || fixedPointResidual>1e-9
    error('GKE:FixedPoint','%s did not reach a valid fixed point.',condition.name);
end

fprintf('%s: constructing Jacobian at its manipulation-specific equilibrium.\n', ...
    condition.name);
J=sparse(l6ns_controlled_jacobian(setup,operators,fixedPoint));
denseJ=full(J);
[allRightEigenvectors,eigenvalues]=eig(denseJ,'vector');
[~,nearZeroOrder]=sort(abs(eigenvalues),'ascend');
[~,leadingIndex]=max(real(eigenvalues));
[~,mostNegativeIndex]=min(real(eigenvalues));
[~,largestMagnitudeIndex]=max(abs(eigenvalues));
selectedEigenIndices=unique([leadingIndex;mostNegativeIndex; ...
    largestMagnitudeIndex;nearZeroOrder(1:8)],'stable');
eigenModes=struct('Indices',selectedEigenIndices, ...
    'Eigenvalues',eigenvalues(selectedEigenIndices), ...
    'RightVectors',allRightEigenvectors(:,selectedEigenIndices));
clear allRightEigenvectors

[leftSingularVectors,singularMatrix,rightSingularVectors]=svd(denseJ,'econ');
singularValues=diag(singularMatrix);
lowSingularIndices=(numel(singularValues)-7:numel(singularValues))';
highSingularIndices=(1:4)';
singularModes=struct( ...
    'LowIndices',lowSingularIndices, ...
    'LowValues',singularValues(lowSingularIndices), ...
    'LowLeftVectors',leftSingularVectors(:,lowSingularIndices), ...
    'LowRightVectors',rightSingularVectors(:,lowSingularIndices), ...
    'HighIndices',highSingularIndices, ...
    'HighValues',singularValues(highSingularIndices), ...
    'HighLeftVectors',leftSingularVectors(:,highSingularIndices), ...
    'HighRightVectors',rightSingularVectors(:,highSingularIndices));
clear leftSingularVectors singularMatrix rightSingularVectors denseJ

n=numel(fixedPoint)/3;
e=1:2*n; inhibitory=2*n+(1:n);
A=J(e,e); B=J(e,inhibitory); C=J(inhibitory,e); D=J(inhibitory,inhibitory);
H=sparse(D-C*(A\B));
schurEigenvalues=eig(full(H),'vector');
thresholds=[0.001 0.005 0.01 0.025 0.05 0.10];
eigenCounts=arrayfun(@(threshold) sum(abs(eigenvalues)<=threshold),thresholds);
singularCounts=arrayfun(@(threshold) sum(singularValues<=threshold),thresholds);
schurCounts=arrayfun(@(threshold) sum(abs(schurEigenvalues)<=threshold),thresholds);

probabilities=singularValues/sum(singularValues);
entropyEffectiveRank=exp(-sum(probabilities.*log(max(probabilities,eps))));
stableRank=sum(singularValues.^2)/singularValues(1)^2;
frobeniusNorm=norm(J,'fro');
henriciDeparture=sqrt(max(frobeniusNorm^2-sum(abs(eigenvalues).^2),0))/ ...
    max(frobeniusNorm,eps);
relativeBaselineDistance=norm(fixedPoint-context.FixedPoint(:))/ ...
    max(norm(context.FixedPoint(:)),eps);

baselineJacobianRelativeError=NaN;
if condition.name=="baseline"
    baselineJacobianRelativeError=norm(J-setup.Pathway.JBaseline,'fro')/ ...
        max(norm(setup.Pathway.JBaseline,'fro'),eps);
end

summary=table(condition.id,condition.name,condition.group,condition.label, ...
    solver.Converged,fixedPointResidual,solver.Iterations,solver.Seconds, ...
    relativeBaselineDistance,min(fixedPoint),max(fixedPoint), ...
    max(real(eigenvalues)),min(real(eigenvalues)),max(abs(eigenvalues)), ...
    eigenCounts(1),eigenCounts(2),eigenCounts(3),eigenCounts(4), ...
    eigenCounts(5),eigenCounts(6),singularCounts(1),singularCounts(2), ...
    singularCounts(3),singularCounts(4),singularCounts(5),singularCounts(6), ...
    schurCounts(5),stableRank,entropyEffectiveRank,henriciDeparture, ...
    baselineJacobianRelativeError,metadata.MaximumL4RowSumRelativeError, ...
    metadata.MeanL4RowSumRatio,metadata.MeanL4RowSumCV, ...
    metadata.MeanL4TranslationError,metadata.MeanL4Rotation90Error, ...
    'VariableNames',{'id','name','group','label','converged', ...
    'fixedPointResidual','solverIterations','solverSeconds', ...
    'relativeBaselineDistance','minimumFiringRate','maximumFiringRate', ...
    'maximumRealEigenvalue','minimumRealEigenvalue','spectralRadius', ...
    'eigLE0p001','eigLE0p005','eigLE0p01','eigLE0p025','eigLE0p05','eigLE0p10', ...
    'sigmaLE0p001','sigmaLE0p005','sigmaLE0p01','sigmaLE0p025', ...
    'sigmaLE0p05','sigmaLE0p10','schurEigLE0p05','stableRank', ...
    'entropyEffectiveRank','henriciDeparture','baselineJacobianRelativeError', ...
    'maximumL4RowSumRelativeError','meanL4RowSumRatio','meanL4RowSumCV', ...
    'meanL4TranslationError','meanL4Rotation90Error'});
writetable(summary,fullfile(outputRoot,'summaries',condition.name+'.tsv'), ...
    'FileType','text','Delimiter','\t');

equilibrium=struct('S',fixedPoint(1:n),'C',fixedPoint(n+(1:n)), ...
    'I',fixedPoint(2*n+(1:n)));
equilibrium.EWeighted=(1-context.CWeight)*equilibrium.S+ ...
    context.CWeight*equilibrium.C;
equilibrium.ESum=equilibrium.S+equilibrium.C;
save(fullfile(outputRoot,'data',condition.name+'.mat'), ...
    'summary','condition','metadata','operatorAudit','operators','equilibrium', ...
    'fixedPoint','solver','J','eigenvalues','eigenModes','singularValues', ...
    'singularModes','schurEigenvalues','thresholds','-v7.3');
fprintf('%s complete: residual %.3e, maxRe %.6f, eig/sigma <=.05 %d/%d.\n', ...
    condition.name,fixedPointResidual,summary.maximumRealEigenvalue, ...
    summary.eigLE0p05,summary.sigmaLE0p05);
end
